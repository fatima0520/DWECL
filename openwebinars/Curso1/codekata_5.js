// Creamos una variable llamada hasPizza
// Le asignamos el valor true (verdadero)
let hasPizza = true;

// Comprobamos si hasPizza es igual a false
if (hasPizza == false) {

    // Si la condición se cumple, mostramos este mensaje
    console.log("No tengo pizza");

    // Si la primera condición no se cumple,
    // comprobamos si hasPizza es igual a true
} else if (hasPizza == true) {

    // Si esta condición se cumple, mostramos este mensaje
    console.log("Tengo pizza");

    // Si ninguna de las condiciones anteriores se cumple,
    // ejecutamos el bloque else
} else {

    // Mostramos el valor de hasPizza por consola
    console.log(hasPizza);
}